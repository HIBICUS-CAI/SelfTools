#!/usr/bin/env python3
"""Generate src/UnicodeData.inc (case-fold pairs and \\w ranges).

fold(c): Unicode simple case folding (CaseFolding.txt status C+S) derived from
Python's unicodedata:  casefold() if it yields one code point, else lower() if
it yields one code point, else c itself.
word(c): .NET-regex-compatible \\w = [\\p{L}\\p{Mn}\\p{Nd}\\p{Pc}]
"""
import sys
import unicodedata
from pathlib import Path


def fold(cp: int) -> int:
    ch = chr(cp)
    f = ch.casefold()
    if len(f) == 1:
        return ord(f)
    lo = ch.lower()
    if len(lo) == 1:
        return ord(lo)
    return cp


def is_word(cp: int) -> bool:
    cat = unicodedata.category(chr(cp))
    return cat[0] == "L" or cat in ("Mn", "Nd", "Pc")


def main() -> None:
    cps = [c for c in range(0x110000) if not (0xD800 <= c <= 0xDFFF)]
    pairs = []
    for c in cps:
        f = fold(c)
        if f != c:
            assert fold(f) == f, hex(c)
            pairs.append((c, f))

    ranges = []
    start = None
    for c in range(0x110001):
        w = c <= 0x10FFFF and not (0xD800 <= c <= 0xDFFF) and is_word(c)
        if w and start is None:
            start = c
        elif not w and start is not None:
            ranges.append((start, c - 1))
            start = None

    out = [
        "// Generated by tools/gen_unicode.py  (Unicode %s). Do not edit." % unicodedata.unidata_version,
        "// clang-format off",
        "static const uint32_t kFoldPairs[][2] = {",
    ]
    for i in range(0, len(pairs), 6):
        out.append("    " + " ".join("{0x%05X,0x%05X}," % p for p in pairs[i:i + 6]))
    out.append("};")
    out.append("static const uint32_t kWordRanges[][2] = {")
    for i in range(0, len(ranges), 6):
        out.append("    " + " ".join("{0x%05X,0x%05X}," % r for r in ranges[i:i + 6]))
    out.append("};")
    out.append("// clang-format on")
    dst = Path(__file__).resolve().parent.parent / "src" / "UnicodeData.inc"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    # max class size (for information)
    classes = {}
    for c, f in pairs:
        classes.setdefault(f, {f}).add(c)
    print("pairs=%d ranges=%d maxClass=%d" % (len(pairs), len(ranges), max(len(v) for v in classes.values())), file=sys.stderr)


if __name__ == "__main__":
    main()
